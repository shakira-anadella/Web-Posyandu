def konversi_usia_ke_bulan_v3(teks_usia):
    if pd.isna(teks_usia):
        return np.nan
    angka = [int(s) for s in re.findall(r'\d+', str(teks_usia))]
    if len(angka) >= 3:
        return round((angka[0] * 12) + angka[1] + (angka[2] / 30.0), 2)
    elif len(angka) == 1:
        return float(angka[0])
    return np.nan

