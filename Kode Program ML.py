target_cols = ['BB/U', 'TB/U', 'BB/TB']
best_parameters_by_target = {}
studies_by_target = {}

for col in target_cols:
    print(f"\n" + "="*60)
    print(f"--- MEMULAI OPTIMASI OPTUNA UNTUK TARGET: {col} ---")
    print("="*60)

    y_target_asli = y_train[col].astype(int)

    def objective(trial):
        params = {
            'n_estimators': trial.suggest_int('n_estimators', 50, 300, step=25),
            'max_depth': trial.suggest_int('max_depth', 3, 9),
            'learning_rate': trial.suggest_float('learning_rate', 0.01, 0.2, log=True),
            'subsample': trial.suggest_float('subsample', 0.6, 1.0),
            'colsample_bytree': trial.suggest_float('colsample_bytree', 0.6, 1.0),
            'random_state': 42,
            'eval_metric': 'mlogloss',
        }

        from imblearn.over_sampling import SMOTE

        skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
        fold_accuracies = []

        for train_idx, val_idx in skf.split(X_train, y_target_asli):
            X_fold_train, X_fold_val = X_train.iloc[train_idx], X_train.iloc[val_idx]
            y_fold_train, y_fold_val = y_target_asli.iloc[train_idx], y_target_asli.iloc[val_idx]

            smote_internal = SMOTE(k_neighbors=1, random_state=42)
            X_fold_train_smote, y_fold_train_smote = smote_internal.fit_resample(X_fold_train, y_fold_train)

            X_fold_train_smote['JK'] = X_fold_train_smote['JK'].round().astype(int)

            num_classes = len(np.unique(y_fold_train_smote))
            params['num_class'] = num_classes
            params['objective'] = 'multi:softprob' if num_classes > 2 else 'binary:logistic'

            mapping = {val: idx for idx, val in enumerate(sorted(np.unique(y_fold_train_smote)))}
            y_fold_train_mapped = y_fold_train_smote.map(mapping)
            y_fold_val_mapped = y_fold_val.map(mapping)

            model = xgb.XGBClassifier(**params)
            model.fit(X_fold_train_smote, y_fold_train_mapped)

            preds = model.predict(X_fold_val)
            fold_accuracies.append(accuracy_score(y_fold_val_mapped, preds))

        return np.mean(fold_accuracies)

    study = optuna.create_study(direction='maximize')
    study.optimize(objective, n_trials=25)

    print(f"\n[INFO] OPTIMASI SELESAI UNTUK TARGET: {col}!")
    print(f"-> Akurasi Validasi Terbaik (Rata-rata 5-Fold): {study.best_value * 100:.2f}%")
    print("-> Parameter Terbaik yang Berhasil Dikunci:")
    for key, value in study.best_params.items():
        print(f"   * {key}: {value}")

    best_parameters_by_target[col] = study.best_params
    studies_by_target[col] = study

